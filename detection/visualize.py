__all__ = ["vis"]


def vis(img, boxes, scores, cls_ids, conf=0.5, class_names=None, text_dis=True):
    """
    在图像上绘制检测框与标签。
    返回 (叠加后的图像, 状态字典)。
    """
    det_img = img.copy()
    mask_img = img.copy()

    for i in range(len(boxes)):
        box = boxes[i]
        cls_id = int(cls_ids[i])
        score = scores[i]
        if score < conf:
            continue
        x0 = int(box[0])
        y0 = int(box[1])
        x1 = int(box[2])
        y1 = int(box[3])

        color = (_COLORS[cls_id % len(_COLORS)] * 255).astype(np.uint8).tolist()
        text = '{}:{:.1f}%'.format(class_names[cls_id], score * 100)
        txt_color = (0, 0, 0) if np.mean(_COLORS[cls_id % len(_COLORS)]) > 0.5 else (255, 255, 255)

        txt_size = cv2.getTextSize(text, FONT_SIZE, 0.5, 1)[0]
        txt_bk_color = (_COLORS[cls_id % len(_COLORS)] * 255 * 0.7).astype(np.uint8).tolist()

        # 画检测框
        cv2.rectangle(det_img, (x0, y0), (x1, y1), color, 2)
        cv2.rectangle(mask_img, (x0, y0), (x1, y1), color, -1)

        if text_dis:
            txt_len = (len(text) - 3) * FONT_SIZE
            cv2.rectangle(
                det_img, (x0, y0 + 1), (x0 + txt_len, y0 + int(1.5 * txt_size[1])),
                txt_bk_color, -1)
            cv2.rectangle(
                mask_img, (x0, y0 + 1), (x0 + txt_len, y0 + int(1.5 * txt_size[1])),
                txt_bk_color, -1)

            det_img = putText(det_img, text, (x0, y0), color=txt_color)
            mask_img = putText(mask_img, text, (x0, y0), color=txt_color)

    return cv2.addWeighted(mask_img, 0.3, det_img, 1 - 0.3, 0)


